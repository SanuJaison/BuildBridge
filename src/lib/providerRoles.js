export const PROVIDER_ROLE_MAP = new Map(PROVIDER_ROLES.map((role) => [role.value, role]));

export function roleLabel(value) {
  return PROVIDER_ROLE_MAP.get(value)?.label || "Provider";
}

export function roleMeta(value) {
  return PROVIDER_ROLE_MAP.get(value) || null;
}

export function rolesForProvider(provider) {
  if (!provider) return [];
  const values = Array.isArray(provider.roles) ? provider.roles : [];
  return values.map((value) => PROVIDER_ROLE_MAP.get(value)).filter(Boolean);
}

